using Login.Data;
using Login.Models;
using Microsoft.AspNetCore.Mvc;
using System.Linq;

namespace Login.Controllers
{
    public class StudentController : Controller
    {
        private readonly AppDbContext _context;

        // Injecting our database context into the controller
        public StudentController(AppDbContext context)
        {
            _context = context;
        }

        // 1. GET: Displays the Registration Form on the Homepage
        [HttpGet]
        public IActionResult Index()
        {
            return View();
        }

        // 2. POST: Handles submission of the form
        [HttpPost]
        [ValidateAntiForgeryToken]
        public IActionResult Index(Student student)
        {
            // 💡 FIX 1: Remove "Id" validation since it's auto-generated by the database
            ModelState.Remove("Id");

            // 💡 FIX 2: Check for existing email to prevent duplicate entry database crashes
            if (!string.IsNullOrEmpty(student.Email))
            {
                var cleanEmail = student.Email.Trim().ToLower();
                var emailExists = _context.Students.Any(s => s.Email.Trim().ToLower() == cleanEmail);

                if (emailExists)
                {
                    ModelState.AddModelError("Email", "This email address is already registered.");
                }
            }

            if (ModelState.IsValid)
            {
                // Clean up string data inputs
                student.Email = student.Email?.Trim();
                student.RegistrationDate = DateTime.Now;
                _context.Students.Add(student); // Stages the data
                _context.SaveChanges();        // Saves data to the database table

                TempData["SuccessMessage"] = "Registration Successful!";
                return RedirectToAction("Success");
            }

            // 💡 FIX 3: If validation still fails, this captures the hidden errors 
            // so you can review them or print them inside your View.
            var errors = ModelState.Values.SelectMany(v => v.Errors).Select(e => e.ErrorMessage);
            TempData["ErrorMessage"] = "Validation failed: " + string.Join(", ", errors);

            // Reload the page with the submitted data and errors visible
            return View(student);
        }

        // 3. GET: Displays the Success Page
        [HttpGet]
        public IActionResult Success()
        {
            return View();
        }
        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> Create(Student student)
        {
            if (ModelState.IsValid)
            {
                // 3. Add the student data to the EF DbSet
                _context.Students.Add(student);

                // 4. Save changes directly to StudentMarkDb
                await _context.SaveChangesAsync();

                // 5. Set the success alert message seen at the bottom of your HTML
                TempData["SuccessMessage"] = "Account created successfully!";

                // Redirect back to the form page or a success view
                return RedirectToAction("Index", "Home");
            }

            // If there's an error or missing fields, reload the page with validation errors
            return View("~/Views/Home/Index.cshtml", student);
        }
    }
}
